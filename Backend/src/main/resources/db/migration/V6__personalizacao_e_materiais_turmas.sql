ALTER TABLE turmas ADD COLUMN descricao VARCHAR(500) NOT NULL DEFAULT '';
ALTER TABLE turmas ADD COLUMN cor VARCHAR(7) NOT NULL DEFAULT '#315A8A';

CREATE TABLE horarios_turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id BIGINT NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
    disciplina VARCHAR(60) NOT NULL,
    dia_semana INTEGER NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    inicio TIME NOT NULL,
    fim TIME NOT NULL,
    professor_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT ck_horario_periodo CHECK (inicio < fim),
    CONSTRAINT uq_horario_inicio UNIQUE (turma_id, dia_semana, inicio)
);
CREATE INDEX idx_horarios_turma ON horarios_turma(turma_id, dia_semana);

CREATE TABLE materiais_turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id BIGINT NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
    professor_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    disciplina VARCHAR(60) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    conteudo VARCHAR(4000) NOT NULL,
    publicado BOOLEAN NOT NULL DEFAULT FALSE,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_materiais_turma ON materiais_turma(turma_id, publicado);
