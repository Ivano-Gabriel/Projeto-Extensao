CREATE TABLE transferencias_turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    origem_turma_id BIGINT NOT NULL,
    destino_turma_id BIGINT NOT NULL,
    direcao_id BIGINT NOT NULL,
    ano_letivo INTEGER NOT NULL,
    criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transferencia_turma_distinta CHECK (origem_turma_id <> destino_turma_id)
);
CREATE INDEX idx_transferencias_escola_aluno
    ON transferencias_turma(escola_id, aluno_id, criada_em);
