CREATE TABLE comunicados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escolas(id) ON DELETE CASCADE,
    turma_id BIGINT REFERENCES turmas(id) ON DELETE CASCADE,
    autor_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    publico VARCHAR(20) NOT NULL CHECK (publico IN ('TODOS','ALUNOS','FUNCIONARIOS')),
    titulo VARCHAR(120) NOT NULL,
    texto VARCHAR(1500) NOT NULL,
    importante BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_comunicados_escola_data ON comunicados(escola_id, criado_em DESC);
CREATE INDEX idx_comunicados_turma ON comunicados(turma_id);
