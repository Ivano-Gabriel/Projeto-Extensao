CREATE TABLE escolas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE usuarios ADD COLUMN escola_id BIGINT REFERENCES escolas(id);
ALTER TABLE usuarios ADD COLUMN administrador_plataforma BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX idx_usuarios_escola ON usuarios(escola_id);

CREATE TABLE turmas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escolas(id),
    codigo VARCHAR(32) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    ano_letivo INTEGER NOT NULL CHECK (ano_letivo BETWEEN 2020 AND 2100),
    UNIQUE (escola_id, codigo, ano_letivo)
);
CREATE INDEX idx_turmas_escola ON turmas(escola_id);

CREATE TABLE matriculas (
    turma_id BIGINT NOT NULL REFERENCES turmas(id),
    aluno_id BIGINT NOT NULL REFERENCES usuarios(id),
    ano_letivo INTEGER NOT NULL,
    PRIMARY KEY (turma_id, aluno_id),
    UNIQUE (aluno_id, ano_letivo)
);

CREATE TABLE vinculos_docentes (
    turma_id BIGINT NOT NULL REFERENCES turmas(id),
    professor_id BIGINT NOT NULL REFERENCES usuarios(id),
    disciplina VARCHAR(60) NOT NULL,
    PRIMARY KEY (turma_id, professor_id, disciplina)
);
CREATE INDEX idx_vinculos_professor ON vinculos_docentes(professor_id);
