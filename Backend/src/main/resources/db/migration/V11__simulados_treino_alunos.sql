CREATE TABLE simulados_estudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escolas(id) ON DELETE CASCADE,
    aluno_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    turma_id BIGINT NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
    disciplina VARCHAR(60) NOT NULL,
    tema VARCHAR(300) NOT NULL,
    dificuldade VARCHAR(12) NOT NULL CHECK (dificuldade IN ('FACIL','MEDIO','DIFICIL')),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalizado_em TIMESTAMP,
    nota INTEGER CHECK (nota BETWEEN 0 AND 10)
);
CREATE INDEX idx_simulados_aluno ON simulados_estudo(aluno_id,escola_id,id);

CREATE TABLE simulados_questoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    simulado_id BIGINT NOT NULL REFERENCES simulados_estudo(id) ON DELETE CASCADE,
    ordem INTEGER NOT NULL CHECK (ordem BETWEEN 1 AND 5),
    titulo VARCHAR(150) NOT NULL,
    pergunta VARCHAR(500) NOT NULL,
    opcao_a VARCHAR(200) NOT NULL,
    opcao_b VARCHAR(200) NOT NULL,
    opcao_c VARCHAR(200) NOT NULL,
    opcao_d VARCHAR(200) NOT NULL,
    correta INTEGER NOT NULL CHECK (correta BETWEEN 0 AND 3),
    explicacao VARCHAR(1000) NOT NULL,
    opcao_marcada INTEGER CHECK (opcao_marcada BETWEEN 0 AND 3),
    UNIQUE(simulado_id,ordem)
);
CREATE INDEX idx_simulados_questoes ON simulados_questoes(simulado_id,ordem);
