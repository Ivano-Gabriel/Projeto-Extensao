CREATE TABLE aulas_registradas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escolas(id) ON DELETE CASCADE,
    turma_id BIGINT NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
    professor_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    disciplina VARCHAR(60) NOT NULL,
    data_aula DATE NOT NULL,
    ordem_aula SMALLINT NOT NULL CHECK (ordem_aula BETWEEN 1 AND 8),
    tema VARCHAR(160) NOT NULL,
    criada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(turma_id,disciplina,data_aula,ordem_aula)
);
CREATE INDEX idx_aulas_escola_turma ON aulas_registradas(escola_id,turma_id,data_aula);

CREATE TABLE presencas_aula (
    aula_id BIGINT NOT NULL REFERENCES aulas_registradas(id) ON DELETE CASCADE,
    aluno_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    presente BOOLEAN NOT NULL,
    registrado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(aula_id,aluno_id)
);
CREATE INDEX idx_presencas_aluno ON presencas_aula(aluno_id);
