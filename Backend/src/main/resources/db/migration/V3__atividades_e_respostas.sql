CREATE TABLE atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escola_id BIGINT NOT NULL REFERENCES escolas(id),
    turma_id BIGINT NOT NULL REFERENCES turmas(id),
    professor_id BIGINT NOT NULL REFERENCES usuarios(id),
    disciplina VARCHAR(60) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_atividades_turma ON atividades(turma_id);
CREATE INDEX idx_atividades_escola ON atividades(escola_id);

CREATE TABLE questoes_atividade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atividade_id BIGINT NOT NULL UNIQUE REFERENCES atividades(id),
    pergunta VARCHAR(500) NOT NULL,
    opcao_a VARCHAR(200) NOT NULL,
    opcao_b VARCHAR(200) NOT NULL,
    opcao_c VARCHAR(200) NOT NULL,
    opcao_d VARCHAR(200) NOT NULL,
    correta INTEGER NOT NULL CHECK (correta BETWEEN 0 AND 3),
    explicacao VARCHAR(1000) NOT NULL
);
CREATE TABLE respostas_atividade (
    questao_id BIGINT NOT NULL REFERENCES questoes_atividade(id),
    aluno_id BIGINT NOT NULL REFERENCES usuarios(id),
    opcao INTEGER NOT NULL CHECK (opcao BETWEEN 0 AND 3),
    respondido_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (questao_id,aluno_id)
);
